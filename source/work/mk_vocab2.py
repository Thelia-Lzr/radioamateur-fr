def main():
    with open(SRC, encoding='utf-8') as f:
        data = json.load(f)

    rows, missing = [], []
    for item in data:
        key = item['key']
        if key not in GLOSS:
            missing.append(key)
            continue
        zh, cat, theme, note = GLOSS[key]
        if not zh:                      # entree volontairement vide = ignoree
            missing.append(key)
            continue
        form = CORR.get(key, item['form'])
        rows.append([form, zh, cat, item['freq'], theme, note])

    with open(DEST, 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerows(rows)

    extra = sorted(k for k in GLOSS if k not in {i['key'] for i in data})
    print('entrees en entree / 输入条数 : %d' % len(data))
    print('lignes ecrites   / 输出行数 : %d' % len(rows))
    print('cles ignorees    / 跳过条数 : %d' % len(missing))
    print('  -> %s' % ', '.join(missing))
    if extra:
        print('cles de GLOSS absentes du JSON : %s' % ', '.join(extra))
    print('fichier          / 文件     : %s (%.1f Ko)'
          % (DEST, os.path.getsize(DEST) / 1024.0))


if __name__ == '__main__':
    main()
