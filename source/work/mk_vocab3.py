def fix_form(key, form):
    """Rend la graphie francaise corrigee (accents, majuscules, tirets)."""
    if key in FORMS:
        return FORMS[key]
    out = []
    for w in form.split(' '):
        out.append(ACC.get(w, w))
    return ' '.join(out)


def main():
    with open(SRC, encoding='utf-8') as f:
        items = json.load(f)
    # certains termes figurent deux fois dans le lot (freq > 0 et freq = 0) :
    # on ne garde que l'occurrence de plus grande frequence, en respectant l'ordre.
    best, order = {}, []
    for it in items:
        k = it['key']
        if k not in best:
            best[k] = it
            order.append(k)
        elif int(it['freq']) > int(best[k]['freq']):
            best[k] = it
    rows, skipped = [], []
    for k in order:
        it = best[k]
        g = GLOSS.get(k)
        if g is None:
            skipped.append(k)
            continue
        zh, cat, theme, note = g
        if cat not in CATS:
            print('!! catégorie inconnue pour %s : %s' % (k, cat))
        if theme not in THEMES:
            print('!! thème inconnu pour %s : %s' % (k, theme))
        rows.append([fix_form(k, it['form']), zh, cat, int(it['freq']), theme, note])
    # deux clefs peuvent donner la meme graphie (ex. « filtre passe bas » et
    # « filtre passe-bas ») : on garde la ligne de plus grande frequence, comme
    # le fera la fusion finale des trois lots.
    uniq, rang = {}, []
    for r in rows:
        f = r[0].lower()
        if f not in uniq:
            uniq[f] = r
            rang.append(f)
        elif r[3] > uniq[f][3]:
            uniq[f] = r
    rows = [uniq[f] for f in rang]
    with open(DEST, 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerows(rows)
    hors_gloss = [k for k in GLOSS if k not in best]
    if hors_gloss:
        print('!! clefs de GLOSS absentes du lot : %s' % ', '.join(sorted(hors_gloss)))
    print('entrées en lecture      : %d' % len(items))
    print('clefs distinctes        : %d' % len(order))
    print('lignes écrites          : %d' % len(rows))
    print('clefs ignorées          : %d' % len(skipped))
    print('clefs ignorées (liste)  : %s' % ', '.join(skipped))
    print('-> %s (%.1f Ko)' % (DEST, os.path.getsize(DEST) / 1024.0))
    return 0


if __name__ == '__main__':
    sys.exit(main())
