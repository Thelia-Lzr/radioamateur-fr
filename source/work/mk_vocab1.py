    with open(DEST, 'w', encoding='utf-8', newline='') as f:
        w = csv.writer(f, lineterminator='\n')
        w.writerows(rows)
    print('entrées en lecture      : %d' % len(items))
    print('lignes écrites          : %d' % len(rows))
    print('entrées ignorées        : %d' % len(skipped))
    print('clés ignorées           : %s' % ', '.join(skipped))
    print('-> %s (%.1f Ko)' % (DEST, os.path.getsize(DEST) / 1024.0))
    return 0


